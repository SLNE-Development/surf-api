package dev.slne.surf.api.common.invoker

import dev.slne.surf.api.shared.api.util.InternalSurfApi
import java.lang.classfile.ClassFile
import java.lang.classfile.CodeBuilder
import java.lang.classfile.TypeKind
import java.lang.constant.ClassDesc
import java.lang.constant.ConstantDescs
import java.lang.constant.DynamicConstantDesc
import java.lang.constant.MethodTypeDesc
import java.lang.invoke.MethodHandle
import java.lang.invoke.MethodHandles
import java.lang.invoke.MethodType

/**
 * Generates and defines hidden classes that implement interface methods by calling constant
 * [MethodHandle]s.
 *
 * The class data of such a hidden class is a `List<MethodHandle>`. The method at index `i` of
 * [generate] calls the handle at index `i` with `invokeExact`, so that handle's type must equal the
 * method's type exactly. Each handle is resolved once per hidden class and is a constant to the
 * JIT.
 *
 * surf-api's invoker factories and surf-nats share this generator.
 */
@InternalSurfApi
object HandleInvokerClasses {

    /**
     * Generates a class named [name] that implements [interfaceType] with [methods].
     *
     * Define the result with [instantiate] and one handle per method, in the order of [methods].
     *
     * @param name the binary name of the class, in the package of the defining lookup
     * @param interfaceType the implemented interface
     * @param methods the interface methods to implement
     * @return the class file bytes
     */
    fun generate(
        name: ClassDesc,
        interfaceType: ClassDesc,
        methods: List<InvokerMethod>,
    ): ByteArray {
        return ClassFile.of().build(name) { classBuilder ->
            // final synthetic class <name> implements <interfaceType>
            classBuilder.withFlags(ClassFile.ACC_FINAL or ClassFile.ACC_SYNTHETIC)
            classBuilder.withInterfaceSymbols(interfaceType)

            // public <init>() { super(); }
            classBuilder.withMethodBody(
                ConstantDescs.INIT_NAME,
                ConstantDescs.MTD_void,
                ClassFile.ACC_PUBLIC,
            ) { codeBuilder ->
                codeBuilder.aload(0)
                    .invokespecial(
                        ConstantDescs.CD_Object,
                        ConstantDescs.INIT_NAME,
                        ConstantDescs.MTD_void,
                    )
                    .return_()
            }

            methods.forEachIndexed { index, method ->
                // public final R name(P...) { return classDataAt(index).invokeExact(...); }
                classBuilder.withMethodBody(
                    method.name,
                    method.type,
                    ClassFile.ACC_PUBLIC or ClassFile.ACC_FINAL,
                ) { codeBuilder ->
                    codeBuilder.callHandle(index, method.type)
                }
            }
        }
    }

    /**
     * Defines [classBytes] as a hidden class of [lookup] with [handles] as class data and returns a
     * new instance of it.
     *
     * [lookup] needs full privilege access, and the generated class name must lie in the package of
     * its lookup class. The hidden class is initialized and can be unloaded once nothing references
     * it.
     *
     * @param lookup the lookup that defines the hidden class
     * @param classBytes a class generated by [generate]
     * @param handles one handle per generated method, in the order of its methods
     * @return a new instance of the hidden class
     * @throws IllegalAccessException if [lookup] lacks full privilege access
     */
    fun instantiate(
        lookup: MethodHandles.Lookup,
        classBytes: ByteArray,
        handles: List<MethodHandle>,
    ): Any {
        val hidden = lookup.defineHiddenClassWithClassData(classBytes, handles, true)
        return hidden
            .findConstructor(hidden.lookupClass(), MethodType.methodType(Void.TYPE))
            .invoke()
    }

    private fun CodeBuilder.callHandle(index: Int, type: MethodTypeDesc) {
        ldc(classDataAt(index))

        var slot = 1

        for (parameter in type.parameterList()) {
            val kind = TypeKind.from(parameter)
            loadLocal(kind, slot)
            slot += kind.slotSize()
        }

        invokevirtual(ConstantDescs.CD_MethodHandle, "invokeExact", type)
        return_(TypeKind.from(type.returnType()))
    }

    // MethodHandles.classDataAt(lookup, "_", MethodHandle.class, index)
    private fun classDataAt(index: Int): DynamicConstantDesc<MethodHandle> {
        @Suppress("PLATFORM_CLASS_MAPPED_TO_KOTLIN")
        return DynamicConstantDesc.ofNamed(
            ConstantDescs.BSM_CLASS_DATA_AT,
            ConstantDescs.DEFAULT_NAME,
            ConstantDescs.CD_MethodHandle,
            index as Integer,
        )
    }
}

/**
 * One method a class generated by [HandleInvokerClasses] implements.
 *
 * @property name the method's name
 * @property type the method's erased descriptor
 */
@InternalSurfApi
data class InvokerMethod(val name: String, val type: MethodTypeDesc)
