package dev.slne.surf.api.gradle.pluginclass

import com.palantir.javapoet.ClassName
import com.palantir.javapoet.JavaFile
import com.palantir.javapoet.TypeSpec
import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import javax.lang.model.element.Modifier

/**
 * A class the Gradle plugin generates into the plugin's package.
 *
 * @property simpleName simple name of the generated class
 * @property superclass fully qualified name of the surf base class the generated class extends
 * @property namedIn where the build script names its own class instead of the generated one
 */
enum class GeneratedPluginClass(
    val simpleName: String,
    val superclass: String,
    val namedIn: String,
) {
    PAPER_BOOTSTRAPPER(
        "GeneratedSurfBootstrapper",
        "dev.slne.surf.api.paper.plugin.SurfPaperBootstrapper",
        "surfPaperPluginApi { bootstrapper(...) }",
    ),
    PAPER_PLUGIN(
        "GeneratedSurfPlugin",
        "dev.slne.surf.api.paper.plugin.SurfPaperPlugin",
        "surfPaperPluginApi { mainClass(...) }",
    ),
    VELOCITY_PLUGIN(
        "GeneratedSurfPlugin",
        "dev.slne.surf.api.velocity.plugin.SurfVelocityPlugin",
        "velocityPluginFile { main = ... }",
    ),
    MINESTOM_PLUGIN(
        "GeneratedSurfPlugin",
        "dev.slne.surf.api.minestom.plugin.SurfMinestomPlugin",
        "minestomPluginFile { main = ... }",
    );

    /**
     * The fully qualified name of the generated class in [basePackage].
     */
    fun qualifiedName(basePackage: String): String = "$basePackage.$simpleName"
}

/**
 * Writes the Java source of [GeneratedPluginClass] with JavaPoet.
 */
internal object PluginClassGenerator {
    fun generate(kind: GeneratedPluginClass, basePackage: String): JavaFile {
        val type = TypeSpec.classBuilder(kind.simpleName)
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .superclass(kind.superclass.toClassName())
            .addJavadoc(javadoc(kind))

        return JavaFile.builder(basePackage, type.build())
            .indent("  ")
            .skipJavaLangImports(true)
            .build()
    }

    private fun javadoc(kind: GeneratedPluginClass): String {
        val role = when (kind) {
            GeneratedPluginClass.PAPER_BOOTSTRAPPER -> "Paper bootstrapper"
            GeneratedPluginClass.PAPER_PLUGIN -> "Paper plugin main class"
            GeneratedPluginClass.VELOCITY_PLUGIN -> "Velocity plugin main class"
            GeneratedPluginClass.MINESTOM_PLUGIN -> "Minestom plugin main class"
        }
        return "The $role generated by the surf Gradle plugin.\n" +
            "\n" +
            "<p>The surf-api runtime creates the Spring context of the plugin from the package of this class.\n" +
            "Name your own class in ${kind.namedIn} to replace it.\n"
    }

    private fun String.toClassName(): ClassName {
        return ClassName.get(substringBeforeLast('.'), substringAfterLast('.'))
    }
}

/**
 * Generates the classes in [classes] into [outputDirectory], below [basePackage].
 */
@CacheableTask
abstract class GeneratePluginClassesTask : DefaultTask() {

    @get:Input
    abstract val basePackage: Property<String>

    @get:Input
    abstract val classes: ListProperty<GeneratedPluginClass>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val directory = outputDirectory.get().asFile
        directory.deleteRecursively()
        directory.mkdirs()

        for (kind in classes.get()) {
            PluginClassGenerator.generate(kind, basePackage.get()).writeTo(directory)
        }
    }
}
