package dev.slne.surf.api.gradle.pluginclass

import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.io.File
import javax.tools.ToolProvider
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertTrue

class PluginClassGeneratorTest {

    @TempDir
    lateinit var directory: File

    private fun generated(
        kind: GeneratedPluginClass,
        basePackage: String = "com.example.plugin",
    ): String {
        return PluginClassGenerator.generate(kind, basePackage).toString()
    }

    @Test
    fun `Paper bootstrapper extends SurfPaperBootstrapper`() {
        assertEquals(
            """
            package com.example.plugin;

            import dev.slne.surf.api.paper.plugin.SurfPaperBootstrapper;

            /**
             * The Paper bootstrapper generated by the surf Gradle plugin.
             *
             * <p>The surf-api runtime creates the Spring context of the plugin from the package of this class.
             * Name your own class in surfPaperPluginApi { bootstrapper(...) } to replace it.
             */
            public final class GeneratedSurfBootstrapper extends SurfPaperBootstrapper {
            }

            """.trimIndent(),
            generated(GeneratedPluginClass.PAPER_BOOTSTRAPPER),
        )
    }

    @Test
    fun `Paper plugin extends SurfPaperPlugin`() {
        val source = generated(GeneratedPluginClass.PAPER_PLUGIN)

        assertTrue("package com.example.plugin;" in source)
        assertTrue("public final class GeneratedSurfPlugin extends SurfPaperPlugin {" in source)
    }

    @Test
    fun `Velocity plugin keeps the default constructor`() {
        val source = generated(GeneratedPluginClass.VELOCITY_PLUGIN)

        assertTrue("public final class GeneratedSurfPlugin extends SurfVelocityPlugin {" in source)
        assertTrue("GeneratedSurfPlugin(" !in source)
    }

    @Test
    fun `Minestom plugin extends SurfMinestomPlugin and keeps the default constructor`() {
        val source = generated(GeneratedPluginClass.MINESTOM_PLUGIN)

        assertTrue("public final class GeneratedSurfPlugin extends SurfMinestomPlugin {" in source)
        assertTrue("GeneratedSurfPlugin(" !in source)
    }

    @Test
    fun `every generated class points at the place its replacement is named`() {
        for (kind in GeneratedPluginClass.entries) {
            assertTrue(
                "Name your own class in ${kind.namedIn} to replace it." in generated(kind),
                kind.name,
            )
        }
    }

    @Test
    fun `generated classes live in the base package`() {
        val source = generated(GeneratedPluginClass.PAPER_PLUGIN, "org.acme.deep.plugin")

        assertTrue(source.startsWith("package org.acme.deep.plugin;"))
        assertEquals(
            "org.acme.deep.plugin.GeneratedSurfPlugin",
            GeneratedPluginClass.PAPER_PLUGIN.qualifiedName("org.acme.deep.plugin"),
        )
    }

    @Test
    fun `generated sources compile against the surf base classes`() {
        val stubs = mapOf(
            "dev/slne/surf/api/paper/plugin/SurfPaperBootstrapper.java" to
                "package dev.slne.surf.api.paper.plugin; public abstract class SurfPaperBootstrapper {}",
            "dev/slne/surf/api/paper/plugin/SurfPaperPlugin.java" to
                "package dev.slne.surf.api.paper.plugin; public abstract class SurfPaperPlugin {}",
            "dev/slne/surf/api/minestom/plugin/SurfMinestomPlugin.java" to
                "package dev.slne.surf.api.minestom.plugin; public abstract class SurfMinestomPlugin {}",
            "dev/slne/surf/api/velocity/plugin/SurfVelocityPlugin.java" to
                "package dev.slne.surf.api.velocity.plugin; public abstract class SurfVelocityPlugin {}",
        )

        val sources = directory.resolve("src")

        for ((path, content) in stubs) {
            sources.resolve(path).apply { parentFile.mkdirs() }.writeText(
                content,
            )
        }

        // One package per platform: the generated classes of Paper, Velocity and Minestom share a
        // simple name.
        val generatedFiles = GeneratedPluginClass.entries.map { kind ->
            val root = directory.resolve("generated-${kind.name}").apply { mkdirs() }
            PluginClassGenerator.generate(
                kind,
                "com.example.${kind.name.lowercase()}",
            ).writeTo(root)
            root.walkTopDown().single { it.isFile }
        }

        val compiler = assertNotNull(ToolProvider.getSystemJavaCompiler(), "tests run on a JDK")
        val output = directory.resolve("classes").apply { mkdirs() }
        val allSources = sources.walkTopDown().filter { it.isFile }.toList() + generatedFiles
        val exitCode = compiler.run(
            null, null, null,
            "-d", output.path,
            *allSources.map { it.path }.toTypedArray(),
        )

        assertEquals(0, exitCode, "the generated sources must compile")
    }
}
