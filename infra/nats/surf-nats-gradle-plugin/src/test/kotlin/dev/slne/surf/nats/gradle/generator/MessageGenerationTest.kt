package dev.slne.surf.nats.gradle.generator

import dev.slne.surf.nats.gradle.generator.GeneratorHarness.Companion.OPTIONS_IMPORT
import dev.slne.surf.nats.gradle.generator.GeneratorHarness.Companion.PROTO2
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.io.File
import kotlin.test.assertEquals

class MessageGenerationTest {
    @TempDir
    lateinit var temp: File

    private fun harness() = GeneratorHarness(temp)

    private fun messages(body: String, vararg imports: String, input: (GeneratorHarness) -> GeneratorInput = { it.input() }): String {
        val harness = harness().proto(
            "surf/test/v1/messages.proto",
            """
            |$PROTO2
            |package surf.test.v1;
            |$OPTIONS_IMPORT
            |${imports.joinToString("\n") { "import \"$it\";" }}
            |$body
            """.trimMargin(),
        )
        return harness.generateFile("surf/test/v1/Messages.kt", input(harness))
    }

    @Test
    fun `scalars map to Kotlin types with integer encodings`() {
        val text = messages(
            """
            message Scalars {
              optional double d = 1;
              optional float f = 2;
              optional int32 i32 = 3;
              optional uint32 u32 = 4;
              optional fixed32 f32 = 5;
              optional sfixed32 sf32 = 6;
              optional int64 i64 = 7;
              optional uint64 u64 = 8;
              optional sint64 s64 = 9;
              optional fixed64 f64 = 10;
              optional sfixed64 sf64 = 11;
              optional bool b = 12;
              optional string s = 13;
              optional bytes by = 14;
            }
            """
        )
        assertContainsAll(
            text,
            "@Serializable\n@SerialName(\"surf.test.v1.Scalars\")\npublic data class Scalars(",
            "@ProtoNumber(1)\n    public val d: Double,",
            "@ProtoNumber(2)\n    public val f: Float,",
            "@ProtoNumber(3)\n    public val i32: Int,",
            "@ProtoNumber(4)\n    public val u32: Int,",
            "@ProtoNumber(5)\n    @ProtoType(ProtoIntegerType.FIXED)\n    public val f32: Int,",
            "@ProtoNumber(6)\n    @ProtoType(ProtoIntegerType.FIXED)\n    public val sf32: Int,",
            "@ProtoNumber(7)\n    public val i64: Long,",
            "@ProtoNumber(8)\n    public val u64: Long,",
            "@ProtoNumber(9)\n    @ProtoType(ProtoIntegerType.SIGNED)\n    public val s64: Long,",
            "@ProtoNumber(10)\n    @ProtoType(ProtoIntegerType.FIXED)\n    public val f64: Long,",
            "@ProtoNumber(11)\n    @ProtoType(ProtoIntegerType.FIXED)\n    public val sf64: Long,",
            "@ProtoNumber(12)\n    public val b: Boolean,",
            "@ProtoNumber(13)\n    public val s: String,",
            "@ProtoNumber(14)\n    public val `by`: ByteArray,",
        )
    }

    @Test
    fun `every generated file opts in to the generated surf-nats API and experimental serialization`() {
        val text = messages("message A { optional int32 a = 1; }")
        assertContainsAll(
            text,
            "// Generated by surf-nats from surf/test/v1/messages.proto. Do not edit.",
            "@file:OptIn(\n    NatsGeneratedApi::class,\n    ExperimentalSerializationApi::class,\n)",
            "import dev.slne.surf.nats.NatsGeneratedApi",
        )
        assertNotContains(text, "InternalNatsApi")
    }

    @Test
    fun `field names become lowerCamel properties and keywords are escaped`() {
        val text = messages("message A { optional string display_name = 1; optional int32 object = 2; optional int32 foo_1 = 3; }")
        assertContainsAll(text, "public val displayName: String,", "public val `object`: Int,", "public val foo1: Int,")
    }

    @Test
    fun `properties follow ascending field numbers instead of the declaration order`() {
        val text = messages(
            """
            message A {
              optional string c = 3;
              optional int64 a = 1;
              optional int32 b = 2;
            }
            """
        )
        assertContainsAll(
            text,
            "public data class A(\n    @ProtoNumber(1)\n    public val a: Long,\n    @ProtoNumber(2)\n    public val b: Int,\n" +
                    "    @ProtoNumber(3)\n    public val c: String,\n)",
        )
    }

    @Test
    fun `a oneof sits at the position of its lowest case number and its cases follow their numbers`() {
        val text = messages(
            """
            message A {
              optional int32 z = 5;
              oneof choice { string text = 4; int32 number = 2; }
              optional int32 a = 3;
            }
            """
        )
        assertInOrder(text, "val choice:", "val a:", "val z:", "class Number(", "class Text(")
    }

    @Test
    fun `reordering field declarations does not change the generated Kotlin`() {
        fun generate(root: String, body: String) = GeneratorHarness(temp.resolve(root)).proto(
            "surf/test/v1/messages.proto",
            """
            |$PROTO2
            |package surf.test.v1;
            |$OPTIONS_IMPORT
            |$body
            """.trimMargin(),
        ).generateFile("surf/test/v1/Messages.kt")

        val declared = generate(
            "declared",
            """
            message A {
              optional string c = 3;
              oneof target { string server = 6; int64 player = 4; }
              optional int64 a = 1;
              optional int32 b = 2 [default = 7];
              optional bytes payload = 5 [(surf.nats.v1.nullable) = true];
            }
            """.trimIndent(),
        )
        val reordered = generate(
            "reordered",
            """
            message A {
              optional bytes payload = 5 [(surf.nats.v1.nullable) = true];
              optional int32 b = 2 [default = 7];
              oneof target { int64 player = 4; string server = 6; }
              optional int64 a = 1;
              optional string c = 3;
            }
            """.trimIndent(),
        )
        assertEquals(declared, reordered)
        assertInOrder(
            declared,
            "public data class A(",
            "val a: Long,",
            "val b: Int = 7,",
            "val c: String,",
            "val target: Target? = null,",
            "val payload: ByteArray? = null,",
            "natsContentEquals(this.payload, other.payload)",
            "class Player(",
            "class Server(",
        )
    }

    @Test
    fun `nullable fields default to null and required fields have no default`() {
        val text = messages(
            """
            message A {
              optional string required = 1;
              optional string optional_name = 2 [(surf.nats.v1.nullable) = true];
              optional int32 count = 3 [(surf.nats.v1.nullable) = false];
              optional B inner = 4 [(surf.nats.v1.nullable) = true];
            }
            message B { optional int32 x = 1; }
            """
        )
        assertContainsAll(
            text,
            "public val required: String,",
            "public val optionalName: String? = null,",
            "public val count: Int,",
            "public val `inner`: B? = null,",
        )
    }

    @Test
    fun `repeated and map fields default to empty collections`() {
        val text = messages(
            """
            message A {
              repeated string tags = 1;
              map<string, int64> counters = 2;
              repeated B items = 3;
            }
            message B { optional int32 x = 1; }
            """
        )
        assertContainsAll(
            text,
            "public val tags: List<String> = emptyList(),",
            "public val counters: Map<String, Long> = emptyMap(),",
            "public val items: List<B> = emptyList(),",
        )
    }

    @Test
    fun `mapped types carry their serializer on the type, also inside type arguments`() {
        val text = messages(
            """
            message A {
              optional google.protobuf.Timestamp at = 1;
              optional google.protobuf.Duration took = 2 [(surf.nats.v1.nullable) = true];
              repeated surf.types.v1.Uuid players = 3;
              map<string, surf.types.v1.Component> names = 4;
              optional surf.types.v1.Key key = 5;
            }
            """,
            "google/protobuf/timestamp.proto", "google/protobuf/duration.proto",
            "surf/types/v1/uuid.proto", "surf/types/v1/component.proto", "surf/types/v1/key.proto",
        )
        assertContainsAll(
            text,
            "public val at: @Serializable(with = TimestampSerializer::class) Instant,",
            "public val took: @Serializable(with = DurationSerializer::class) Duration? = null,",
            "List<@Serializable(with = UuidSerializer::class) UUID> = emptyList(),",
            "Map<String, @Serializable(with = ComponentSerializer::class) Component> = emptyMap(),",
            "public val key: @Serializable(with = KeySerializer::class) Key,",
            "import java.time.Instant",
            "import kotlin.time.Duration",
            "import java.util.UUID",
            "import net.kyori.adventure.text.Component",
            "import net.kyori.adventure.key.Key",
            "import dev.slne.surf.nats.types.TimestampSerializer",
        )
    }

    @Test
    fun `paper types are mapped only for paper projects`() {
        val text = messages(
            "message A { optional surf.types.paper.v1.Location at = 1; optional surf.types.paper.v1.ItemStack item = 2; }",
            "surf/types/paper/v1/location.proto", "surf/types/paper/v1/item_stack.proto",
            input = { it.input(paperTypes = true) },
        )
        assertContainsAll(
            text,
            "public val at: @Serializable(with = LocationSerializer::class) Location,",
            "public val item: @Serializable(with = ItemStackSerializer::class) ItemStack,",
            "import org.bukkit.Location",
            "import org.bukkit.inventory.ItemStack",
            "import dev.slne.surf.nats.paper.types.LocationSerializer",
        )
    }

    @Test
    fun `mapType overrides and adds mappings and suppresses generation of mapped source messages`() {
        val text = messages(
            """
            message Tag { optional string value = 1; }
            message A { optional Tag tag = 1; optional google.protobuf.Timestamp at = 2; }
            """,
            "google/protobuf/timestamp.proto",
            input = {
                it.input(
                    mappings = listOf(
                        TypeMapping("surf.test.v1.Tag", "dev.example.Tag", "dev.example.TagSerializer"),
                        TypeMapping("google.protobuf.Timestamp", "kotlin.time.Instant", "dev.example.InstantSerializer"),
                    )
                )
            },
        )
        assertContainsAll(
            text,
            "public val tag: @Serializable(with = TagSerializer::class) Tag,",
            "public val at: @Serializable(with = InstantSerializer::class) Instant,",
            "import kotlin.time.Instant",
        )
        assertNotContains(text, "class Tag", "java.time.Instant")
    }

    @Test
    fun `fieldless messages become plain classes with generated equality`() {
        val text = messages("message Ping {}")
        assertContainsAll(
            text,
            "@Serializable\n@SerialName(\"surf.test.v1.Ping\")\npublic class Ping {",
            "override fun equals(other: Any?): Boolean = other is Ping",
            "override fun hashCode(): Int = ",
            "override fun toString(): String = \"Ping()\"",
        )
        assertNotContains(text, "data class Ping")
    }

    @Test
    fun `byte array properties get content-aware equals, hashCode and toString`() {
        val text = messages(
            """
            message Blob {
              optional bytes data = 1;
              repeated bytes chunks = 2;
              map<string, bytes> parts = 3;
              optional string name = 4;
            }
            """
        )
        assertContainsAll(
            text,
            "return natsContentEquals(this.`data`, other.`data`) && natsContentEquals(this.chunks, other.chunks) && " +
                    "natsContentEquals(this.parts, other.parts) && this.name == other.name",
            "var result = natsContentHashCode(this.`data`)",
            "result = 31 * result + natsContentHashCode(this.chunks)",
            "result = 31 * result + this.name.hashCode()",
            "\"Blob(data=\" + natsContentToString(this.`data`) + \", chunks=\" + natsContentToString(this.chunks)",
            "import dev.slne.surf.nats.descriptor.natsContentEquals",
        )
    }

    @Test
    fun `content-aware members qualify properties that shadow their locals`() {
        val text = messages("message A { optional bytes other = 1; optional int32 result = 2; }")
        assertContainsAll(
            text,
            "return natsContentEquals(this.other, other.other) && this.result == other.result",
            "var result = natsContentHashCode(this.other)\n        result = 31 * result + this.result.hashCode()",
            "\"A(other=\" + natsContentToString(this.other) + \", result=\" + this.result + \")\"",
        )
    }

    @Test
    fun `content-aware equals compares floating point properties by their bits like data classes`() {
        val text = messages(
            """
            message Sample {
              optional bytes data = 1;
              optional double value = 2;
              optional float ratio = 3;
              optional double maybe = 4 [(surf.nats.v1.nullable) = true];
              optional float maybe_ratio = 5 [(surf.nats.v1.nullable) = true];
            }
            """
        )
        assertContainsAll(
            text,
            "natsContentEquals(this.`data`, other.`data`) && this.`value`.toBits() == other.`value`.toBits() && " +
                    "this.ratio.toBits() == other.ratio.toBits() && this.maybe?.toBits() == other.maybe?.toBits() && " +
                    "this.maybeRatio?.toBits() == other.maybeRatio?.toBits()",
            "result = 31 * result + this.`value`.hashCode()",
        )
    }

    @Test
    fun `messages without byte arrays keep the data class equality`() {
        val text = messages("message A { optional string a = 1; }")
        assertNotContains(text, "override fun equals", "natsContent")
    }

    @Test
    fun `nested messages and enums become nested classes`() {
        val text = messages(
            """
            message Outer {
              optional Inner inner = 1;
              optional Kind kind = 2;
              message Inner { optional int32 x = 1; }
              enum Kind { KIND_UNSPECIFIED = 0; KIND_A = 1; }
            }
            message Other { optional Outer.Inner inner = 1; }
            """
        )
        assertContainsAll(
            text,
            "public val `inner`: Inner,",
            "public val kind: Kind,",
            "    @SerialName(\"surf.test.v1.Outer.Inner\")\n    public data class Inner(",
            "    public enum class Kind(",
            "public val `inner`: Outer.Inner,",
        )
    }

    @Test
    fun `oneofs become a nullable property and a sealed interface with data class cases`() {
        val text = messages(
            """
            message A {
              oneof target {
                string server = 1;
                sint64 region = 2;
                B other = 3;
                bytes raw = 4;
                google.protobuf.Timestamp at = 5;
              }
            }
            message B { optional int32 x = 1; }
            """,
            "google/protobuf/timestamp.proto",
        )
        assertContainsAll(
            text,
            "@ProtoOneOf\n    public val target: Target? = null,",
            "@Serializable\n    public sealed interface Target {",
            "@Serializable\n        public data class Server(\n            @ProtoNumber(1)\n            public val `value`: String,\n        ) : Target",
            "@ProtoNumber(2)\n            @ProtoType(ProtoIntegerType.SIGNED)\n            public val `value`: Long,",
            "@ProtoNumber(3)\n            public val `value`: B,",
            "@ProtoNumber(5)\n            public val `value`: @Serializable(with = TimestampSerializer::class) Instant,",
            "if (other !is Raw) return false",
        )
    }

    @Test
    fun `generated enums strip the value prefix and fall back to the zero entry`() {
        val text = messages(
            """
            enum PunishmentType {
              PUNISHMENT_TYPE_UNSPECIFIED = 0;
              PUNISHMENT_TYPE_BAN = 1;
              PUNISHMENT_TYPE_TEMP_BAN = 5;
            }
            enum HttpStatus { HTTP_STATUS_UNKNOWN = 0; HTTP_STATUS_OK = 200; }
            """
        )
        assertContainsAll(
            text,
            "@Serializable(with = PunishmentType.Serializer::class)\npublic enum class PunishmentType(\n    public val number: Int,\n) {",
            "    UNSPECIFIED(0),\n    BAN(1),\n    TEMP_BAN(5),\n    ;",
            "public object Serializer : KSerializer<PunishmentType> {",
            "PrimitiveSerialDescriptor(\"surf.test.v1.PunishmentType\", PrimitiveKind.INT)",
            "encoder.encodeInt(value.number)",
            "0 -> PunishmentType.UNSPECIFIED\n            1 -> PunishmentType.BAN\n            5 -> PunishmentType.TEMP_BAN\n" +
                    "            else -> PunishmentType.UNSPECIFIED",
            "    UNKNOWN(0),\n    OK(200),",
            "else -> HttpStatus.UNKNOWN",
        )
    }

    @Test
    fun `map integer encodings follow the non-default side`() {
        val text = messages(
            """
            enum Color { COLOR_UNSPECIFIED = 0; COLOR_RED = 1; }
            message A {
              map<string, sint64> signed_values = 1;
              map<fixed32, string> fixed_keys = 2;
              map<int32, Color> colors = 3;
              map<fixed64, double> fixed_doubles = 4;
              map<string, int32> plain = 5;
            }
            """
        )
        assertContainsAll(
            text,
            "@ProtoNumber(1)\n    @ProtoType(ProtoIntegerType.SIGNED)\n    public val signedValues: Map<String, Long>",
            "@ProtoNumber(2)\n    @ProtoType(ProtoIntegerType.FIXED)\n    public val fixedKeys: Map<Int, String>",
            "@ProtoNumber(3)\n    public val colors: Map<Int, Color>",
            "@ProtoNumber(4)\n    @ProtoType(ProtoIntegerType.FIXED)\n    public val fixedDoubles: Map<Long, Double>",
            "@ProtoNumber(5)\n    public val plain: Map<String, Int>",
        )
    }

    @Test
    fun `packed repeated fields get ProtoPacked exactly when declared packed`() {
        val text = messages(
            """
            enum Color { COLOR_UNSPECIFIED = 0; COLOR_RED = 1; }
            message A {
              repeated int32 packed_ints = 1 [packed = true];
              repeated int32 plain_ints = 2;
              repeated Color packed_colors = 3 [packed = true];
              repeated double packed_doubles = 4 [packed = true];
              repeated bool flags = 5 [packed = false];
              repeated fixed32 fixed_values = 6;
            }
            """
        )
        assertContainsAll(
            text,
            "@ProtoNumber(1)\n    @ProtoPacked\n    public val packedInts: List<Int>",
            "@ProtoNumber(2)\n    public val plainInts: List<Int>",
            "@ProtoNumber(3)\n    @ProtoPacked\n    public val packedColors: List<Color>",
            "@ProtoNumber(4)\n    @ProtoPacked\n    public val packedDoubles: List<Double>",
            "@ProtoNumber(5)\n    public val flags: List<Boolean>",
            "@ProtoNumber(6)\n    @ProtoType(ProtoIntegerType.FIXED)\n    public val fixedValues: List<Int>",
        )
    }

    @Test
    fun `java_package selects the Kotlin package`() {
        val files = harness().proto(
            "surf/test/v1/a.proto",
            """
            $PROTO2
            package surf.test.v1;
            option java_package = "dev.example.proto.v1";
            message A { optional int32 a = 1; }
            """
        ).generate()
        assertEquals(listOf("dev/example/proto/v1/A.kt"), files.keys.toList())
        assertContainsAll(files.values.single(), "package dev.example.proto.v1")
    }

    @Test
    fun `files without messages or services produce no Kotlin file`() {
        val files = harness()
            .proto("surf/test/v1/a.proto", "$PROTO2\npackage surf.test.v1;\nmessage A { optional int32 a = 1; }")
            .proto("surf/test/v1/empty.proto", "$PROTO2\npackage surf.test.v1;")
            .generate()
        assertEquals(listOf("surf/test/v1/A.kt"), files.keys.toList())
    }

    @Test
    fun `no proto sources produce an empty result`() {
        val harness = harness()
        harness.sourceDir.mkdirs()
        assertEquals(emptyMap(), harness.generate())
    }

    @Test
    fun `internal visibility applies to declarations only`() {
        val text = harness().proto(
            "surf/test/v1/all.proto",
            """
            $PROTO2
            package surf.test.v1;
            $OPTIONS_IMPORT
            import "google/protobuf/empty.proto";
            enum Color { COLOR_UNSPECIFIED = 0; COLOR_RED = 1; }
            message Event {
              option (surf.nats.v1.event) = {};
              optional bytes data = 1;
              oneof choice { string a = 2; int32 b = 3; }
              message Nested { optional int32 x = 1; }
            }
            message Ping {}
            service CalcService { rpc Ping(surf.test.v1.Ping) returns (google.protobuf.Empty); }
            """
        ).generateFile("All.kt", GeneratorHarness(temp).input(visibility = GeneratedVisibility.INTERNAL))
        assertContainsAll(
            text,
            "internal enum class Color(",
            "internal data class Event(",
            "internal sealed interface Choice {",
            "        public data class A(",
            "internal data class Nested(",
            "internal class Ping {",
            "internal interface CalcService {",
            "public val NATS_DESCRIPTOR: NatsServiceDescriptor<CalcService>",
            "public val NATS_DESCRIPTOR: NatsEventDescriptor<Event>",
            "public companion object {",
            "public object Serializer : KSerializer<Color>",
            "public val number: Int,",
            "public val `data`: ByteArray,",
        )
        assertNotContains(
            text,
            "internal val", "internal fun", "internal companion", "internal object", "internal override", "internal data class A(",
        )
    }
}
