package dev.slne.surf.microservice.processor

import com.tschuchort.compiletesting.KotlinCompilation.ExitCode
import dev.slne.surf.microservice.processor.support.ProcessorRun
import dev.slne.surf.microservice.processor.support.SourceGeneratingProcessorProvider
import dev.slne.surf.microservice.processor.support.TestSources
import dev.slne.surf.microservice.processor.support.TestSources.microserviceApi
import org.jetbrains.kotlin.compiler.plugin.ExperimentalCompilerApi
import kotlin.test.Test
import kotlin.test.assertContains
import kotlin.test.assertEquals

@OptIn(ExperimentalCompilerApi::class)
class MultiRoundProcessingTest {

    @Test
    fun `finds a microservice class generated by another processor`() {
        val generator = SourceGeneratingProcessorProvider(
            packageName = "com.example.generated",
            fileName = "GeneratedMicroservice",
            code = """
                package com.example.generated
                object GeneratedMicroservice : dev.slne.surf.microservice.api.Microservice()
                """
        )

        val run = ProcessorRun.compile(microserviceApi, additionalProviders = listOf(generator))

        assertEquals(ExitCode.OK, run.exitCode, run.messages)
        assertEquals(
            "com.example.generated.GeneratedMicroservice",
            run.resource(MicroserviceResources.MAIN_CLASS_PATH)
        )
    }

    @Test
    fun `resolves a microservice class whose base class is generated in a later round`() {
        val generator = SourceGeneratingProcessorProvider(
            packageName = "com.example.generated",
            fileName = "GeneratedBase",
            code = """
                package com.example.generated
                abstract class GeneratedBase : dev.slne.surf.microservice.api.Microservice()
                """
        )
        val service = TestSources.kotlin(
            "PunishMicroservice.kt",
            """
            package com.example
            class PunishMicroservice : com.example.generated.GeneratedBase()
            """
        )

        val run = ProcessorRun.compile(microserviceApi, service, additionalProviders = listOf(generator))

        assertEquals(ExitCode.OK, run.exitCode, run.messages)
        assertEquals("com.example.PunishMicroservice", run.resource(MicroserviceResources.MAIN_CLASS_PATH))
    }

    @Test
    fun `resolves a nested class whose base class is generated in a later round`() {
        val generator = SourceGeneratingProcessorProvider(
            packageName = "com.example.generated",
            fileName = "GeneratedBase",
            code = """
                package com.example.generated
                abstract class GeneratedBase : dev.slne.surf.microservice.api.Microservice()
                """
        )
        val service = TestSources.kotlin(
            "PunishMicroservice.kt",
            """
            package com.example
            class Outer {
                class PunishMicroservice : com.example.generated.GeneratedBase()
            }
            """
        )

        val run = ProcessorRun.compile(microserviceApi, service, additionalProviders = listOf(generator))

        assertEquals(ExitCode.OK, run.exitCode, run.messages)
        assertEquals("com.example.Outer\$PunishMicroservice", run.resource(MicroserviceResources.MAIN_CLASS_PATH))
    }

    @Test
    fun `names classes whose supertypes stay unresolved`() {
        val service = TestSources.kotlin(
            "PunishMicroservice.kt",
            """
            package com.example
            class PunishMicroservice : com.example.missing.MissingBase()
            """
        )

        val run = ProcessorRun.compile(microserviceApi, service)

        assertEquals(ExitCode.COMPILATION_ERROR, run.exitCode)
        assertContains(run.messages, "Cannot resolve the supertypes of com.example.PunishMicroservice")
    }
}
