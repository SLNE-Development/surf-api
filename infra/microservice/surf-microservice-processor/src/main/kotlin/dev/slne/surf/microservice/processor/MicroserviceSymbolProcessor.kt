package dev.slne.surf.microservice.processor

import com.google.devtools.ksp.getClassDeclarationByName
import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.KSPLogger
import com.google.devtools.ksp.processing.Resolver
import com.google.devtools.ksp.processing.SymbolProcessor
import com.google.devtools.ksp.symbol.KSAnnotated
import com.google.devtools.ksp.symbol.KSClassDeclaration
import dev.slne.surf.microservice.processor.MicroserviceResources.MAIN_CLASS_PATH
import dev.slne.surf.microservice.processor.MicroserviceResources.MICROSERVICE_CLASS
import dev.slne.surf.microservice.processor.MicroserviceResources.MIGRATIONS_PATH
import dev.slne.surf.microservice.processor.MicroserviceResources.SURF_MIGRATION_CLASS
import dev.slne.surf.microservice.processor.declaration.classDeclarations
import dev.slne.surf.microservice.processor.declaration.instantiationProblems
import dev.slne.surf.microservice.processor.declaration.isConcrete
import dev.slne.surf.microservice.processor.declaration.supertypeNamesOrNull

/**
 * Writes the [MAIN_CLASS_PATH] and [MIGRATIONS_PATH] resources of a microservice module.
 *
 * Each round inspects the files that are new in that round: all sources of the module in the first round, the files
 * generated by other processors afterwards. Classes whose supertypes are not resolvable yet are inspected again in the
 * next round. The resources are written once in [finish], as aggregating outputs of the discovered classes' files.
 *
 * The build fails if the module has no or more than one concrete [MICROSERVICE_CLASS] subclass, or if a discovered
 * class cannot be instantiated reflectively.
 */
internal class MicroserviceSymbolProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
) : SymbolProcessor {
    private val microservices = DiscoveredClasses()
    private val migrations = DiscoveredClasses()
    private var unresolvedClassNames = emptySet<String>()

    override fun process(resolver: Resolver): List<KSAnnotated> {
        val retriedClasses = unresolvedClassNames.mapNotNull { resolver.getClassDeclarationByName(it) }
        val newClasses = resolver.getNewFiles().flatMap { it.classDeclarations() }
        val stillUnresolved = HashSet<String>()

        for (declaration in (retriedClasses.asSequence() + newClasses).filter { it.isConcrete() }) {
            val supertypeNames = declaration.supertypeNamesOrNull()
            if (supertypeNames == null) {
                declaration.qualifiedName?.let { stillUnresolved += it.asString() }
            } else {
                classify(declaration, supertypeNames)
            }
        }

        unresolvedClassNames = stillUnresolved
        return emptyList()
    }

    private fun classify(declaration: KSClassDeclaration, supertypeNames: Set<String>) {
        when {
            MICROSERVICE_CLASS in supertypeNames -> discover(declaration, "Microservice", microservices)
            SURF_MIGRATION_CLASS in supertypeNames -> discover(declaration, "Migration", migrations)
        }
    }

    private fun discover(declaration: KSClassDeclaration, kind: String, target: DiscoveredClasses) {
        val problems = declaration.instantiationProblems()
        if (problems.isEmpty()) {
            target.add(declaration)
        } else {
            val name = declaration.qualifiedName?.asString()
            logger.error("$kind $name cannot be instantiated by the runtime: ${problems.joinToString("; ")}", declaration)
        }
    }

    override fun finish() {
        if (unresolvedClassNames.isNotEmpty()) {
            logger.error("Cannot resolve the supertypes of ${unresolvedClassNames.sorted().joinToString()}")
            return
        }
        writeMainClass()
        writeMigrations()
    }

    private fun writeMainClass() {
        when (microservices.size) {
            0 -> logger.error("No concrete subclass of $MICROSERVICE_CLASS found in this module")
            1 -> writeResource(MAIN_CLASS_PATH, microservices)
            else -> logger.error(
                "Found ${microservices.size} concrete subclasses of $MICROSERVICE_CLASS in this module, " +
                    "expected exactly one: ${microservices.qualifiedNames.joinToString()}"
            )
        }
    }

    private fun writeMigrations() {
        if (migrations.size > 0) {
            writeResource(MIGRATIONS_PATH, migrations)
        }
    }

    private fun writeResource(path: String, classes: DiscoveredClasses) {
        codeGenerator.createNewFileByPath(classes.dependencies(), path, extensionName = "")
            .bufferedWriter(Charsets.UTF_8)
            .use { it.write(classes.binaryNames.joinToString("\n")) }
    }
}
