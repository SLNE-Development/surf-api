package dev.slne.surf.microservice.gradle.plugin

import com.bmuschko.gradle.docker.tasks.image.Dockerfile
import org.gradle.api.GradleException
import org.gradle.api.provider.Provider
import java.io.File

internal const val DOCKER_APPLICATION_JAR_NAME = "app.jar"

private const val BUILD_STAGE_NAME = "build"
private const val COMMAND_CLIENT_BUILD_STAGE_NAME = "command-client-build"
private const val APPLICATION_USER = "app"
private const val APPLICATION_GROUP = "app"
private const val APPLICATION_UID = 10_001
private const val APPLICATION_GID = 10_001

private const val DEFAULT_JVM_OPTIONS =
    "-XX:MaxRAMPercentage=75.0 " +
            "-XX:+ExitOnOutOfMemoryError"

private const val GENERATED_MARKER =
    "# Generated by dev.slne.surf.microservice (generateMicroserviceDockerfile)."

private const val COMMAND_CLIENT_EXECUTABLE = "microservicectl"
private const val COMMAND_CLIENT_SOURCE_FILE = "/src/main.go"
private const val COMMAND_CLIENT_OUTPUT_FILE = "/out/microservicectl"
private const val COMMAND_CLIENT_INSTALL_PATH = "/usr/local/bin/microservicectl"
private const val COMMAND_SOCKET_ENVIRONMENT_VARIABLE = "SURF_MICROSERVICE_COMMAND_SOCKET"
private const val COMMAND_SOCKET_PATH = "/app/run/microservice.sock"

internal fun Dockerfile.configureMicroserviceDockerfile(
    overwrite: Provider<Boolean>,
    builderImage: Provider<String>,
    commandClientBuilderImage: Provider<String>,
    baseImage: Provider<String>,
    runnableTaskPath: Provider<String>,
    runnableArtifactPath: Provider<String>,
    commandClientSourcePath: Provider<String>
) {
    val dockerfileTask = this

    inputs.property("surfMicroservice.docker.overwrite", overwrite)

    outputs.doNotCacheIf(
        "Generation must preserve manual Dockerfile overwrite protection."
    ) {
        true
    }

    doFirst {
        val destination = dockerfileTask.destFile.get().asFile

        destination.parentFile?.mkdirs()
        protectExistingDockerfile(destination, overwrite.get(), dockerfileTask.path)
    }

    comment("syntax=docker/dockerfile:1")
    instruction(GENERATED_MARKER)
    comment("Manual changes are lost the next time this file is generated.\n")

    comment("Stage 1: build the runnable application JAR with Gradle.")

    from(
        builderImage.map { image ->
            Dockerfile.From(image).apply {
                withStage(BUILD_STAGE_NAME)
            }
        }
    )

    workingDir("/workspace")
    copyFile(".", ".")

    runCommand(
        runnableTaskPath.map { task ->
            "chmod +x gradlew && ./gradlew $task --no-daemon"
        }
    )

    section("Stage 2: compile the native $COMMAND_CLIENT_EXECUTABLE command client.")

    from(
        commandClientBuilderImage.map { image ->
            Dockerfile.From(image).apply {
                withStage(COMMAND_CLIENT_BUILD_STAGE_NAME)
            }
        }
    )

    workingDir("/src")

    copyFile(
        commandClientSourcePath.map { sourcePath ->
            Dockerfile.CopyFile(
                "/workspace/${sourcePath.asDockerContextPath()}",
                COMMAND_CLIENT_SOURCE_FILE
            ).apply {
                withStage(BUILD_STAGE_NAME)
            }
        }
    )

    // language="Shell Script"
    runCommand(
        """
        mkdir -p /out \
            && CGO_ENABLED=0 go build \
                -buildvcs=false \
                -trimpath \
                -ldflags='-s -w' \
                -o $COMMAND_CLIENT_OUTPUT_FILE \
                $COMMAND_CLIENT_SOURCE_FILE
        """.trimIndent()
    )

    section("Stage 3: assemble the runtime image.")

    from(
        baseImage.map { image ->
            Dockerfile.From(image)
        }
    )

    section("Run the application as an unprivileged user that owns /app.")

    // language="Shell Script"
    runCommand(
        """
        groupadd --system --gid $APPLICATION_GID $APPLICATION_GROUP \
            && useradd --system \
                --uid $APPLICATION_UID \
                --gid $APPLICATION_GROUP \
                --home-dir /app \
                --create-home \
                $APPLICATION_USER
        """.trimIndent()
    )

    section("Install the application JAR and the command client.")

    workingDir("/app")

    copyFile(
        runnableArtifactPath.map { artifactPath ->
            Dockerfile.CopyFile(
                "/workspace/${artifactPath.asDockerContextPath()}",
                "/app/$DOCKER_APPLICATION_JAR_NAME"
            ).apply {
                withStage(BUILD_STAGE_NAME)
                withChown("$APPLICATION_USER:$APPLICATION_GROUP")
            }
        }
    )

    instruction(
        "COPY --from=$COMMAND_CLIENT_BUILD_STAGE_NAME " +
                "$COMMAND_CLIENT_OUTPUT_FILE " +
                COMMAND_CLIENT_INSTALL_PATH
    )

    section(
        "Additional JVM flags. The entrypoint always applies:",
        "  $DEFAULT_JVM_OPTIONS"
    )

    instruction("ENV JAVA_OPTS=\"\"")

    section("Unix socket used by $COMMAND_CLIENT_EXECUTABLE to reach the running application.")

    environmentVariable(COMMAND_SOCKET_ENVIRONMENT_VARIABLE, COMMAND_SOCKET_PATH)

    section("Start the application; arguments passed to the container are forwarded to it.")

    user(APPLICATION_USER)

    instruction(
        $$"""ENTRYPOINT ["sh", "-c", "exec java $$DEFAULT_JVM_OPTIONS $JAVA_OPTS -jar /app/$$DOCKER_APPLICATION_JAR_NAME \"$@\"", "--"]"""
    )
}

private fun Dockerfile.section(vararg lines: String) {
    instruction(
        lines.joinToString(
            separator = "\n# ",
            prefix = "\n# ",
        )
    )
}

private fun Dockerfile.comment(comment: String) {
    instructions.add(Dockerfile.CommentInstruction(comment))
}

internal fun File.relativeToDockerContext(
    contextDirectory: File,
): String {
    val contextPath = contextDirectory
        .toPath()
        .toAbsolutePath()
        .normalize()

    val targetPath = toPath()
        .toAbsolutePath()
        .normalize()

    if (!targetPath.startsWith(contextPath)) {
        throw GradleException(
            "The runnable artifact must be inside the Docker build context: $targetPath"
        )
    }

    return contextPath
        .relativize(targetPath)
        .toString()
        .replace(File.separatorChar, '/')
}

private fun String.asDockerContextPath(): String {
    val normalized = replace('\\', '/').removePrefix("./")

    val invalid =
        normalized.isBlank() ||
                normalized.startsWith('/') ||
                normalized.split('/').any { segment -> segment == ".." }

    if (invalid) {
        throw GradleException(
            "The runnable artifact must be inside the Docker build context: $this"
        )
    }

    return normalized
}

private fun protectExistingDockerfile(
    destination: File,
    overwrite: Boolean,
    taskPath: String,
) {
    if (!destination.exists() || overwrite) {
        return
    }

    val generated = destination.useLines(Charsets.UTF_8) { lines ->
        lines.any { line -> line == GENERATED_MARKER }
    }

    if (generated) {
        return
    }

    throw GradleException(
        "Refusing to overwrite ${destination.absolutePath} because it was not generated by " +
                "$taskPath. Move the file, add the generated marker, or set " +
                "surfMicroservice.docker.overwrite to true."
    )
}
